import { useState } from 'react';
import { Link, useNavigate, useParams } from 'react-router-dom';
import { useApi, useAction } from '../api/hooks.js';
import { post, patch } from '../api/client.js';
import { Badge, Button, Card, ConfirmDialog, DemoBadge, EmptyState, ErrorState, Field, LoadingCard, Modal, ScoreBadge } from '../components/ui.jsx';
import { ContactIndicator, EvidencePanel, ScoreFactors, SignalBadge, VerificationBadge } from '../components/OpportunityParts.jsx';
import { date, humanize, NEGOTIATION_LABELS, negotiationTone, relative } from '../lib/format.js';

function AddContact({ oppId, onDone }) {
  const [v, setV] = useState({ name: '', role: '', businessEmail: '', sourceUrl: '' });
  const add = useAction((body) => post(`/opportunities/${oppId}/contacts`, body), { invalidate: [['opportunity', oppId]], success: 'Contact added (private to you)', onSuccess: onDone });
  return (
    <form className="stack" onSubmit={(e) => { e.preventDefault(); add.mutate({ name: v.name || null, role: v.role || null, businessEmail: v.businessEmail, ...(v.sourceUrl ? { sourceUrl: v.sourceUrl } : {}) }); }}>
      <p className="small muted">Only add business contacts you obtained lawfully (e.g. a public partnerships page or a direct introduction). Manually added contacts are unverified and visible only to you.</p>
      <div className="grid cols-2">
        <Field label="Name">{(p) => <input {...p} className="input" value={v.name} onChange={(e) => setV({ ...v, name: e.target.value })} />}</Field>
        <Field label="Role">{(p) => <input {...p} className="input" value={v.role} onChange={(e) => setV({ ...v, role: e.target.value })} placeholder="e.g. Influencer Marketing Manager" />}</Field>
      </div>
      <Field label="Business email">{(p) => <input {...p} className="input" type="email" required value={v.businessEmail} onChange={(e) => setV({ ...v, businessEmail: e.target.value })} />}</Field>
      <Field label="Where you found it (URL, optional)">{(p) => <input {...p} className="input" value={v.sourceUrl} onChange={(e) => setV({ ...v, sourceUrl: e.target.value })} placeholder="https://" />}</Field>
      <div className="row" style={{ justifyContent: 'flex-end' }}><Button type="submit" variant="primary" loading={add.isPending}>Add contact</Button></div>
    </form>
  );
}

function PitchComposer({ opp }) {
  const navigate = useNavigate();
  const contacts = opp.contacts.filter((c) => c.businessEmail && !c.doNotContact);
  const [draft, setDraft] = useState(opp.pitchDraft?.body ? { subject: opp.pitchDraft.subject, body: opp.pitchDraft.body, provider: opp.pitchDraft.provider } : null);
  const [contactId, setContactId] = useState(opp.pitchDraft?.contactId || contacts[0]?._id || '');
  const [confirm, setConfirm] = useState(false);
  const generate = useAction(() => post(`/opportunities/${opp._id}/draft-pitch`), {
    invalidate: [['opportunity', opp._id]],
    onSuccess: (d) => setDraft({ subject: d.subject, body: d.body, provider: d.provider, fallbackReason: d.fallbackReason }),
  });
  const initiate = useAction(() => post(`/opportunities/${opp._id}/initiate-outreach`, { contactId, subject: draft.subject, body: draft.body }), {
    invalidate: ['opportunities', 'approvals', 'dashboard', ['opportunity', opp._id], 'conversations'],
    success: (r) => (r.autoAuthorized ? 'Pitch queued under your automation rules' : 'Pitch sent to your approval queue — nothing has been sent yet'),
    onSuccess: (r) => {
      setConfirm(false);
      navigate(r.autoAuthorized ? `/inbox?conversation=${r.conversationId}` : `/approvals?focus=${r.approvalId}`);
    },
  });
  const openDeal = opp.outreachHistory.find((h) => h.status === 'open');
  if (opp.excluded) return <div className="callout danger">This brand is excluded by your policy: {opp.exclusionReason}. Update your brand preferences to reconsider it.</div>;
  if (openDeal) {
    return (
      <div className="callout info">
        You already have an open conversation with this brand. <Link to={`/negotiations/${openDeal.dealId}`}>Open negotiation →</Link>
      </div>
    );
  }
  return (
    <div className="stack">
      {!draft ? (
        <EmptyState title="No pitch drafted yet" icon="sparkle" action={<Button variant="primary" icon="sparkle" loading={generate.isPending} onClick={() => generate.mutate()}>Draft a pitch</Button>}>
          The AI writes a personalised pitch from the evidence above. Nothing is sent until you approve it.
        </EmptyState>
      ) : (
        <>
          <div className="row wrap">
            <Badge tone="ai">AI draft · not sent</Badge>
            <span className="tiny faint">Generated by {draft.provider === 'mock' ? 'development mock (rule-based)' : draft.provider === 'template' ? 'template (AI unavailable)' : draft.provider}</span>
            {draft.fallbackReason && <span className="tiny" style={{ color: 'var(--warning)' }}>Fallback: {draft.fallbackReason}</span>}
          </div>
          <Field label="Send to">
            {(p) =>
              contacts.length ? (
                <select {...p} className="select" value={contactId} onChange={(e) => setContactId(e.target.value)}>
                  {contacts.map((c) => (
                    <option key={c._id} value={c._id}>
                      {c.name || 'Unnamed'} — {c.role || humanize(c.roleCategory)} ({c.businessEmail}) · {Math.round(c.confidence * 100)}% {c.verificationStatus}
                    </option>
                  ))}
                </select>
              ) : (
                <div className="callout warning small">No contactable business email for this brand. Add a contact first.</div>
              )
            }
          </Field>
          <Field label="Subject">{(p) => <input {...p} className="input" value={draft.subject} onChange={(e) => setDraft({ ...draft, subject: e.target.value })} maxLength={200} />}</Field>
          <Field label="Message" hint="A signature and an AI-assistance disclosure with an unsubscribe line are added automatically.">
            {(p) => <textarea {...p} className="textarea" rows={10} value={draft.body} onChange={(e) => setDraft({ ...draft, body: e.target.value })} />}
          </Field>
          <div className="row between wrap">
            <Button icon="refresh" onClick={() => generate.mutate()} loading={generate.isPending}>Regenerate</Button>
            <Button variant="primary" disabled={!contactId || draft.body.trim().length < 20} onClick={() => setConfirm(true)}>Submit for approval</Button>
          </div>
        </>
      )}
      <ConfirmDialog open={confirm} onClose={() => setConfirm(false)} title="Start outreach?" confirmLabel="Create outreach" loading={initiate.isPending} onConfirm={() => initiate.mutate()}>
        <p>This creates a deal and conversation and routes the pitch through your approval policy.</p>
        <p className="small muted">At your current autonomy settings the pitch will wait in the approval queue unless you enabled automatic pitches. You will see exactly what will be sent before anything goes out.</p>
      </ConfirmDialog>
    </div>
  );
}

export default function OpportunityDetailPage() {
  const { id } = useParams();
  const q = useApi(['opportunity', id], `/opportunities/${id}`);
  const [adding, setAdding] = useState(false);
  const feedback = useAction((rating) => post(`/opportunities/${id}/feedback`, { rating }), { invalidate: [['opportunity', id]], success: 'Thanks — feedback recorded' });
  const dnc = useAction(({ contactId, value }) => patch(`/contacts/${contactId}`, { doNotContact: value }), { invalidate: [['opportunity', id]], success: 'Contact preference updated' });

  if (q.isLoading) return <LoadingCard lines={8} />;
  if (q.error) return <ErrorState error={q.error} onRetry={q.refetch} />;
  const o = q.data;
  const facts = o.rationale.filter((r) => r.kind === 'fact');
  const hyps = o.rationale.filter((r) => r.kind === 'hypothesis');

  return (
    <div className="stack lg">
      <div className="page-header">
        <div className="row top">
          <ScoreBadge score={o.excluded ? 0 : o.overallScore} />
          <div>
            <div className="row wrap">
              <h1>{o.brand.name}</h1>
              <DemoBadge show={o.isDemo && o.verificationStatus !== 'demo'} />
              <SignalBadge type={o.signalType} />
              <VerificationBadge status={o.evidenceStale ? 'stale' : o.verificationStatus} />
            </div>
            <p>{o.brand.industry} · <span className="mono">{o.brand.normalizedDomain}</span> · first found {date(o.firstDiscoveredAt)} · last verified {relative(o.lastVerifiedAt)}</p>
          </div>
        </div>
        <div className="btn-group">
          <Button size="sm" onClick={() => feedback.mutate('relevant')} aria-pressed={o.feedback?.rating === 'relevant'}>👍 Relevant</Button>
          <Button size="sm" onClick={() => feedback.mutate('not_relevant')} aria-pressed={o.feedback?.rating === 'not_relevant'}>👎 Not relevant</Button>
        </div>
      </div>

      <div className="split">
        <div className="stack lg">
          <Card title="Why this was discovered">
            <div className="stack">
              {facts.map((r, i) => <div key={i} className="row top"><Badge>Fact</Badge><span>{r.text}</span></div>)}
              {hyps.map((r, i) => <div key={i} className="row top"><Badge tone="ai">Hypothesis</Badge><span className="muted">{r.text}</span></div>)}
              {o.outreachAngle && <div className="callout ai small"><span><strong>Suggested angle:</strong> {o.outreachAngle}</span></div>}
              {o.excluded && <div className="callout danger">{o.exclusionReason}</div>}
            </div>
          </Card>
          <Card title="Fit explanation" actions={<span className="tiny faint">Scoring {o.scoringVersion} · fit {o.fitScore} · timing {o.timingScore}</span>}>
            <ScoreFactors factors={o.scoreFactors} />
          </Card>
          <Card title="Source evidence">
            <EvidencePanel evidence={o.sourceEvidence} stale={o.evidenceStale} />
          </Card>
          <Card title="Recommended pitch">
            <PitchComposer key={o.pitchDraft?.at || 'none'} opp={o} />
          </Card>
        </div>
        <div className="stack lg">
          <Card title="Brand">
            <dl className="kv small">
              <dt>Industry</dt><dd>{o.brand.industry || '—'}</dd>
              <dt>Categories</dt><dd>{(o.brand.categories || []).map(humanize).join(', ') || '—'}</dd>
              <dt>Markets</dt><dd>{(o.brand.markets || []).join(', ') || 'Unknown'}</dd>
              <dt>Product / campaign</dt><dd>{o.productOrCampaign || '—'}</dd>
              <dt>Website</dt><dd className="mono">{o.brand.officialWebsite}</dd>
            </dl>
            {o.brand.brandDescription && <p className="small muted" style={{ marginTop: 10 }}>{o.brand.brandDescription}</p>}
          </Card>
          <Card title="Contacts" actions={<Button size="sm" onClick={() => setAdding(true)}>Add</Button>} bodyClass="">
            {!o.contacts.length ? (
              <EmptyState title="No contacts found" icon="user">We never guess names or emails. Add a contact you found yourself.</EmptyState>
            ) : (
              <div className="list">
                {o.contacts.map((c) => (
                  <div key={c._id} className="list-item" style={{ alignItems: 'flex-start' }}>
                    <div className="grow" style={{ minWidth: 0 }}>
                      <div className="strong">{c.name || 'Name unknown'}</div>
                      <div className="small muted">{c.role || humanize(c.roleCategory)}</div>
                      <div className="small mono truncate">{c.businessEmail || 'No email'}</div>
                      <div className="row wrap" style={{ marginTop: 4 }}>
                        <ContactIndicator contact={c} />
                        {c.ownerCreatorId && <Badge>Added by you</Badge>}
                        {c.lastVerifiedAt && <span className="tiny faint">checked {relative(c.lastVerifiedAt)}</span>}
                      </div>
                    </div>
                    <Button size="sm" variant="ghost" onClick={() => dnc.mutate({ contactId: c._id, value: !c.doNotContact })}>
                      {c.doNotContact ? 'Allow' : 'Do not contact'}
                    </Button>
                  </div>
                ))}
              </div>
            )}
          </Card>
          <Card title="Outreach history" bodyClass="">
            {!o.outreachHistory.length ? (
              <EmptyState title="No outreach yet" icon="mail" />
            ) : (
              <div className="list">
                {o.outreachHistory.map((h) => (
                  <Link key={h.dealId} to={`/negotiations/${h.dealId}`} className="list-item">
                    <span className="grow small">{date(h.createdAt)} · {h.conversation?.messageCount || 0} messages</span>
                    <Badge tone={negotiationTone(h.negotiationState)}>{NEGOTIATION_LABELS[h.negotiationState]}</Badge>
                  </Link>
                ))}
              </div>
            )}
          </Card>
        </div>
      </div>
      <Modal open={adding} onClose={() => setAdding(false)} title="Add a business contact">
        <AddContact oppId={o._id} onDone={() => setAdding(false)} />
      </Modal>
    </div>
  );
}
