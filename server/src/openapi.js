const paths = {};
for (const r of ROUTES) {
  paths[r.path] ??= {};
  paths[r.path][r.method] = {
    summary: r.summary,
    tags: [r.tag],
    security: r.auth ? [{ sessionCookie: [], csrfHeader: [] }] : [],
    ...(r.body ? { description: `Body fields: ${r.body}` } : {}),
    responses: { 200: { description: 'OK' }, 401: { description: 'Not authenticated' }, 403: { description: 'Forbidden / CSRF / policy' }, 404: { description: 'Not found (also returned for records owned by other creators)' }, 409: { description: 'Conflict / invalid state' }, 422: { description: 'Validation failed' } },
  };
}

